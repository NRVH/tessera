/** ¿`palabra` (en mayúsculas) es reservada en el motor `d`? */
export function esReservada(palabra: string, d: DialectoSql): boolean {
  // `deDialecto` y no `RESERVADAS[d]`: con un dialecto desconocido, un error con nombre.
  return deDialecto(RESERVADAS, d).has(palabra.toUpperCase())
}
